const MIDDLE_ZONE = CLIMATE["Москва"]!;

/** У Москвы три аэропорта: город у них общий, а погода — своя у каждого. */
const AIRPORT_CITY: Record<string, string> = {
  SVO: "Москва",
  VKO: "Москва",
  DME: "Москва",
  LED: "Санкт-Петербург",
  SVX: "Екатеринбург",
};

export const cityOf = (place: string) => AIRPORT_CITY[place] ?? place;

/** Дни от эпохи — непрерывная ось, чтобы соседние дни получали близкую погоду. */
export const dayIndex = (date: LocalDate) => {
  const [yy, mm, dd] = date.split("-").map(Number);
  return Date.UTC(yy || 1970, (mm || 1) - 1, dd || 1) / 86_400_000;
};

/** Обратно: сквозной день -> "2026-10-24". */
const dateOf = (day: number): LocalDate =>
  new Date(Math.floor(day) * 86_400_000).toISOString().slice(0, 10);

/**
 * Норма на конкретный день. Значения месяцев стоят на 15-м числе, между ними —
 * линейно, иначе 31 января и 1 февраля отличались бы скачком.
 */
function climateMean(climate: readonly number[], date: LocalDate) {
  const [, mm, dd] = date.split("-").map(Number);
  const month = clamp((mm || 1) - 1, 0, 11);
  const offset = ((dd || 15) - 15) / 30;
  const from = offset < 0 ? (month + 11) % 12 : month;
  const to = (from + 1) % 12;
  const t = offset < 0 ? 1 + offset : offset;
  return climate[from]! + (climate[to]! - climate[from]!) * t;
}

/**
 * Средняя температура дня в городе. Отклонение от нормы тянется днями, как
 * реальные потепления и похолодания. Зимой разброс шире: оттепель и мороз в
 * один месяц для средней полосы — обычное дело.
 */
export function temperatureAt(place: string, date: LocalDate): number {
  const city = cityOf(place);
  const norm = climateMean(CLIMATE[city] ?? MIDDLE_ZONE, date);
  const spread = norm < 0 ? 7 : norm < 10 ? 5 : 4;
  return norm + (noise(`${city}|temp`, dayIndex(date) / 4) - 0.5) * 2 * spread;
}

export type Weather = {
  wind: number;
  fog: number;
  precip: number;
  storm: number;
  gustMs: number;
  visibilityKm: number;
  /** Температура в момент, а не за день: в ней решается, снег это или дождь. */
  temp: number;
  kind: "снег" | "дождь";
  /** Одна сводка 0..1: насколько эта погода угрожает расписанию. */
  impact: number;
};

/**
 * Две октавы на канал: медленная — фронт над городом на день-два, общий для
 * всех его аэропортов; быстрая — колебания внутри него, своя у аэропорта.
 * Шестичасовой узел: два рейса одного вечера делят погоду, утренний и
 * вечерний — нет.
 */
const track = (place: string, channel: string, t: number) =>
  0.65 * noise(`${place}|${channel}`, t / 6) +
  0.35 * noise(`${cityOf(place)}|${channel}|slow`, t / 30);

/**
 * Видимость в км. До тумана средней силы — «более 10 км», дальше падает
 * круто: ниже полутора километров уходит лишь сильный туман, это редкость.
 */
const visibilityFor = (fog: number) =>
  fog < 0.66 ? 10 : Math.max(0.2, 10 * Math.pow(1 - (fog - 0.66) / 0.2, 1.6));

/**
 * С какой силы гроза становится событием. Подобрано по выборке: в тёплые дни
 * так выходит около одного дня из семи, а не каждый второй.
 */
export const STORM = 0.72;

/** Погода в месте (аэропорт или город) на сквозном часе от эпохи. */
export function weatherAt(place: string, hours: number): Weather {
  const day = Math.floor(hours / 24);
  const date = dateOf(day);
  const dayOfYear = day - Date.UTC(Number(date.slice(0, 4)), 0, 1) / 86_400_000;
  // 1 в январе, 0 в июле.
  const season = 0.5 + 0.5 * Math.cos((2 * Math.PI * (dayOfYear + 10)) / 365);

  // Днём теплее, ночью холоднее — на пару градусов, чтобы снег и дождь
  // переходили друг в друга около нуля, а не по календарю.
  const hour = ((hours % 24) + 24) % 24;
  const temp = temperatureAt(place, date) + 2.5 * Math.sin((2 * Math.PI * (hour - 9)) / 24);
  // Гроза — летнее явление: в мороз её нет совсем.
  const warmth = clamp01((temp - 4) / 10);

  // Без постоянной поправки на место: случайная «туманность» города никак не
  // связана с настоящей и только сдвигала пороги — у одного города выходил год
  // без дождя, у другого — полгода облачности. Различия задаёт температура.
  const wind = clamp01(0.6 * track(place, "wind", hours) + 0.125 + 0.15 * season);
  const fog = clamp01(0.6 * track(place, "fog", hours) + 0.1 + 0.2 * season);
  const precip = clamp01(0.6 * track(place, "precip", hours) + 0.1 + 0.2 * season);
  const storm = clamp01(track(place, "storm", hours) * warmth);
  const snow = temp <= 0.5;

  return {
    wind,
    fog,
    precip,
    storm,
    // Медиана порывов ~10 м/с, 14+ — несколько процентов случаев.
    gustMs: Math.round(3 + 14 * wind),
    visibilityKm: Math.round(visibilityFor(fog) * 10) / 10,
    temp,
    kind: snow ? "снег" : "дождь",
    // Боковой ветер закрывает полосу чаще всего, поэтому весит больше всех;
    // гроза ложится сверху, снег — вдвое тяжелее дождя: борт ждёт обработки от
    // обледенения. Сумма весов больше 1 намеренно: туман вместе с грозой должны
    // упираться в потолок, а не проходить сквозь него.
    impact: clamp01(0.4 * wind + 0.25 * fog + (snow ? 0.3 : 0.15) * precip + 0.35 * storm),
  };
}

/** «800 м» или «1,2 км» — как пишут в сводках. */
export const formatVisibility = (km: number) =>
  km < 1 ? `${Math.round((km * 1000) / 50) * 50} м` : `${km.toFixed(1).replace(".", ",")} км`;

/** Одно слово для плашки аэропорта — из той же погоды, что и у карточки рейса. */
export function phenomenonOf(weather: Weather): string {
  const { temp } = weather;
  if (weather.storm > STORM) return "Гроза";
  if (weather.visibilityKm < 1.5) return "Туман";
  if (weather.precip > 0.6) {
    if (temp <= -3) return weather.gustMs >= 13 ? "Метель" : "Снег";
    if (temp <= 1.5) return "Мокрый снег";
    return temp >= 18 ? "Кратковременный дождь" : "Дождь";
  }
  if (weather.gustMs >= 14) return `Ветер до ${weather.gustMs} м/с`;
  if (weather.precip > 0.46) return temp >= 18 ? "Переменная облачность" : "Облачно";
  return temp <= -12 ? "Морозная дымка" : "Ясно";
}
